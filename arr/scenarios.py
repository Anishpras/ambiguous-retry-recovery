"""Scenario fixtures, the nominal-attempt rule (PROTOCOL.md §4.1) and the secondary grids (§4.3).

A fixture lists, per operation, overrides for specific attempts. Every attempt a fixture does not
override follows the nominal rule below; extra retries are generated by this documented rule,
never by randomness.

Attempt script fields (times in ticks):
  arrive                  ticks from dispatch to arrival (>= 1), or null: lost before arrival
  decision                "accept" | "reject" (rejected at arrival, never executes)
  commit_after            ticks from arrival to commit                     } exactly one of
  abort_after             ticks from arrival to abort                      } these two
  violation_commit_after  ticks from arrival to a commit *after* the abort (S15 contract violation)
  deferred_after          ticks from arrival to a `deferred` webhook emission (temporary failure);
                          an integer or a list (one emission per entry)
  response                null (lost) or {"kind": override, "after": ticks after the provider decision}
  webhooks                {event: [delivery offsets from emission]}; [] = emitted but lost;
                          absent `processing`/`deferred` = not emitted
Keys starting with "_" are comments and are ignored everywhere. A scenario may carry "options"
(arr/options.py); the option "retry_fault": "copy_first" makes every attempt copy attempt 1's script.
Full format: docs/scenario-format.md.
"""
import copy
import json
import os

from . import ids

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCENARIO_DIR = os.path.join(ROOT, "scenarios")
EXPLORATORY_DIR = os.path.join(SCENARIO_DIR, "exploratory")
CORE_IDS = tuple("S%02d" % i for i in range(16))
ORIGINAL_CORE_IDS = tuple("S%02d" % i for i in range(13))   # scope of the original §7 predictions

# Nominal attempt (§4.1): arrives at +1, accepted, commits 1 tick after arrival, `ok` response
# 1 tick after the commit, `committed` webhook delivered 2 ticks after emission, no `processing`.
NOMINAL = {
    "arrive": 1,
    "decision": "accept",
    "commit_after": 1,
    "abort_after": None,
    "violation_commit_after": None,
    "deferred_after": None,
    "response": {"after": 1},
    "webhooks": {"committed": [2], "aborted": [2]},
}
ALLOWED_FIELDS = set(NOMINAL)
WEBHOOK_EVENTS = ("processing", "deferred", "committed", "aborted")


def resolve_attempt(op, k, retry_fault="nominal"):
    """Script for attempt k of operation `op`: the nominal rule plus the fixture's overrides. With
    retry_fault == "copy_first", an attempt without its own override copies attempt 1's."""
    script = copy.deepcopy(NOMINAL)
    attempts = op.get("attempts", {})
    override = attempts.get(str(k))
    if override is None:
        override = attempts.get("1", {}) if retry_fault == "copy_first" else {}
    for key, val in override.items():
        if key.startswith("_"):
            continue
        if key not in ALLOWED_FIELDS:
            raise ValueError("unknown attempt field %r in %s" % (key, op["op_key"]))
        if key == "webhooks":
            for ev, offs in val.items():
                if ev not in WEBHOOK_EVENTS:
                    raise ValueError("unknown webhook event %r" % ev)
                script["webhooks"][ev] = list(offs)
        elif key == "abort_after":
            script["abort_after"] = val
            script["commit_after"] = None
        else:
            script[key] = copy.deepcopy(val)
    d = script["deferred_after"]
    script["deferred_after"] = [] if d is None else ([d] if isinstance(d, int) else list(d))
    _check_script(script, op["op_key"], k)
    return script


def _check_script(s, op_key, k):
    where = "%s attempt %d" % (op_key, k)
    if s["arrive"] is not None and (not isinstance(s["arrive"], int) or s["arrive"] < 1):
        raise ValueError(where + ": arrive must be >= 1 or null")
    if s["decision"] not in ("accept", "reject"):
        raise ValueError(where + ": bad decision")
    if (s["commit_after"] is None) == (s["abort_after"] is None):
        raise ValueError(where + ": exactly one of commit_after / abort_after")
    if s["violation_commit_after"] is not None and s["abort_after"] is None:
        raise ValueError(where + ": violation commit requires an abort")
    if s["response"] is not None and s["response"].get("after", 1) < 1:
        raise ValueError(where + ": response delay must be >= 1")


def _finish(scn):
    lag = scn["status_lag"]
    scn["lag"] = None if lag == "never" else int(lag)   # None: never visible before F
    for op in scn["operations"]:
        op["payload_hash"] = ids.payload_hash(op["payload"])
        op.setdefault("start", 0)
        for k in (1, 2, 3):
            resolve_attempt(op, k)   # validate eagerly
            resolve_attempt(op, k, "copy_first")
    scn.setdefault("family", "custom")
    scn.setdefault("options", {})
    scn["op_index"] = {op["op_key"]: op for op in scn["operations"]}
    return scn


def attempt_script(scn, logical_op, k, retry_fault="nominal"):
    return resolve_attempt(scn["op_index"][logical_op], k, retry_fault)


def load_json(name):
    with open(os.path.join(SCENARIO_DIR, name), encoding="utf-8") as fh:
        return json.load(fh)


def load_core():
    """The frozen core matrix, in ID order."""
    return [_finish(load_json("%s.json" % sid)) for sid in CORE_IDS]


def load_file(path):
    """Any scenario file (e.g. a practitioner's own), validated with the same rules as the fixtures."""
    with open(path, encoding="utf-8") as fh:
        return _finish(json.load(fh))


def load_exploratory():
    return [load_file(os.path.join(EXPLORATORY_DIR, f)) for f in sorted(os.listdir(EXPLORATORY_DIR))
            if f.endswith(".json")]


def load_scenario(sid):
    if sid.startswith("G"):
        for scn in build_grids():
            if scn["id"] == sid:
                return scn
        raise KeyError(sid)
    if os.path.exists(os.path.join(EXPLORATORY_DIR, "%s.json" % sid)):
        return load_file(os.path.join(EXPLORATORY_DIR, "%s.json" % sid))
    return _finish(load_json("%s.json" % sid))


def fixture_files():
    return sorted(f for f in os.listdir(SCENARIO_DIR) if f.endswith(".json"))


def _grid_value(v):
    return "never" if v == "never" else ("lost" if v == "lost" else str(v))


def build_grids():
    """Secondary deterministic grids (§4.3), generated from scenarios/grids.json in fixed order."""
    spec = load_json("grids.json")
    payload = spec["payload"]
    out = []
    for gname in ("G1", "G2", "G3"):
        g = spec["grids"][gname]
        if gname == "G1":
            combos = [(L, W) for L in g["L"] for W in g["W"]]
        elif gname == "G2":
            combos = [(E, L) for E in g["E"] for L in g["L"]]
        else:
            combos = [(L,) for L in g["L"]]
        for combo in combos:
            if gname == "G1":
                L, W = combo
                a1 = {"commit_after": 1, "response": None,
                      "webhooks": {"committed": [] if W == "lost" else [W]}}
                sid, params = "G1_L%s_W%s" % (_grid_value(L), _grid_value(W)), {"L": L, "W": W}
            elif gname == "G2":
                E, L = combo
                a1 = {"commit_after": E, "response": None, "webhooks": {"committed": [2]}}
                sid, params = "G2_E%s_L%s" % (E, _grid_value(L)), {"E": E, "L": L}
            else:
                (L,) = combo
                a1 = {"arrive": None}
                sid, params = "G3_L%s" % _grid_value(L), {"L": L}
            scn = {"id": sid, "grid": gname, "params": params, "family": "grid_" + gname,
                   "status_lag": params["L"],
                   "operations": [{"op_key": "op-1", "start": 0, "payload": copy.deepcopy(payload),
                                   "attempts": {"1": a1}}]}
            out.append(_finish(scn))
    return out

def sort_rows(rows):
    return sorted(rows, key=lambda r: (r["contract"], POLICY_ORDER[r["policy"]], r["scenario"], r["op"]))


def groups(rows, keyf):
    out = {}
    for r in rows:
        out.setdefault(keyf(r), []).append(r)
    return out


def by_policy_rows(rows):
    out = []
    for scope, ids in (("S00-S15", CORE_IDS), ("S00-S12", ORIGINAL_CORE_IDS)):
        g = groups([r for r in rows if r["scenario"] in ids], lambda r: (r["contract"], POLICY_ORDER[r["policy"]]))
        for (c, _), rs in sorted(g.items()):
            row = {"scope": scope, "contract": c, "policy": rs[0]["policy"], "role": rs[0]["role"]}
            row.update(metrics.aggregate(rs))
            out.append(row)
    return out


def by_family_rows(rows):
    g = groups(rows, lambda r: (r["contract"], POLICY_ORDER[r["policy"]], r["family"]))
    out = []
    for (c, _, fam), rs in sorted(g.items()):
        row = {"contract": c, "policy": rs[0]["policy"], "role": rs[0]["role"], "family": fam}
        row.update(metrics.aggregate(rs))
        out.append(row)
    return out



def worked_traces_md(cell_index, rows):
    lines = ["# Worked traces", "",
             "Generated from the actual run traces (`results/traces/contract1/D/<scenario>.jsonl`). "
             "Columns: what the provider knows (hidden), what the client's policy sees or does, and what the "
             "private scorer records. Effect IDs are opaque HMACs. Ticks with no events are omitted.", ""]
    for sid, title in WORKED:
        sim = cell_index[(1, "D", sid)]
        lines += ["## %s: %s" % (sid, title), "", "Script: " + sim.scenario["protocol_script"], "",
                  "Evidence: " + sim.scenario["evidence"], "", timeline_md(sim), "",
                  "**What every policy did in %s** (from the same run):" % sid, "",
                  "| contract | policy | dispatches | commits (t) | belief at H | effects at H / F | outcome |",
                  "|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["scenario"] != sid:
                continue
            outcome = "duplicate (%s-caused)" % r["dup_cause"] if r["duplicate"] else (
                "exactly once" if r["exactly_once"] else "zero effects")
            lines.append("| %d | %s | %s | %s | %s | %d / %d | %s |" % (
                r["contract"], pname(r["policy"]), r["dispatch_times"], r["commits"] or "none", r["belief_H"],
                r["effects_H"], r["effects_F"], outcome))
        lines.append("")
    return "\n".join(lines) + "\n"

def grid_rows(cells):
    out = []
    for cell in cells:
        scn = cell["scenario_obj"]
        for r in cell["rows"]:
            row = dict(r)
            row.update({"grid": scn["grid"], "schedule": scn["id"], "L": scn["params"].get("L", ""),
                        "W": scn["params"].get("W", ""), "E": scn["params"].get("E", "")})
            out.append(row)
    return out


def _code(r):
    return "%d%s" % (r["effects_F"], {"complete": "C", "failed": "F", "unresolved": "U"}[r["belief_H"]])


def _thr(values, rows_for):
    """Smallest axis value with a duplicate, and whether duplicates persist for all larger values."""
    hits = [v for v in values if rows_for(v) and rows_for(v)["duplicate"]]
    if not hits:
        return "-"
    first = values.index(hits[0])
    tail_all = all(rows_for(v)["duplicate"] for v in values[first:])
    return ("%s" % hits[0]) + ("+" if tail_all and first < len(values) - 1 else ("" if tail_all else " (non-monotone)"))



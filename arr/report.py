def _short(aid):
    return aid.split("#")[-1] if aid else "?"


def describe(e):
    """Map one trace entry to (column, text) for the three-column timeline, or None to skip."""
    ev, d = e["event"], e["details"]
    if ev == "request_lost":
        return "provider", "(network) request %s lost before arrival" % _short(d["attempt_id"])
    if ev == "arrival_accepted":
        return "provider", "%s arrives and is accepted%s" % (_short(d["attempt_id"]),
                                                             " (dedup record created)" if d.get("dedup_record") else "")
    if ev == "arrival_rejected":
        return "provider", "%s arrives and is rejected" % _short(d["attempt_id"])
    if ev in ("dedup_in_progress", "dedup_replay", "dedup_conflict"):
        what = {"dedup_in_progress": "record pending: replies `in_progress`",
                "dedup_replay": "record committed: replies `ok` replaying %s" % d.get("effect_id"),
                "dedup_conflict": "payload differs: replies `conflict`"}[ev]
        return "provider", "%s arrives; %s, no new effect" % (_short(d["attempt_id"]), what)
    if ev == "deferred":
        return "provider", "%s hits a temporary failure; the provider will retry internally" % _short(d["attempt_id"])
    if ev == "commit":
        return "provider", "%s executes and commits effect %s" % (_short(d["attempt_id"]), d["effect_id"])
    if ev == "commit_after_abort":
        return "provider", "%s commits %s after its abort (CONTRACT VIOLATION)" % (_short(d["attempt_id"]), d["effect_id"])
    if ev == "abort":
        return "provider", "%s aborts" % _short(d["attempt_id"])
    if ev == "webhook_emitted":
        where = ("delivery at t = %s" % ", ".join(str(x) for x in d["deliveries"])) if d["deliveries"] else "lost"
        return "provider", "emits `%s` (seq %s) for %s -> %s" % (d["event"], d["provider_seq"], _short(d["attempt_id"]), where)
    if ev == "response_sent":
        return "provider", "sends `%s` response for %s -> arrives t = %s" % (d["kind"], _short(d["attempt_id"]), d["arrives_at"])
    if ev == "response_lost":
        return "provider", "(network) the `%s` response for %s is lost" % (d["kind"], _short(d["attempt_id"]))
    if ev == "status_snapshot":
        if d["cutoff"] is None:
            view = "replica never shows records (L = never)"
        else:
            view = "replica as of t = %s shows %d record(s)" % (d["cutoff"], d["visible_records"])
        truth = "truth now: effects [%s], pending [%s]" % (", ".join(d["true_effects_now"]), ", ".join(d["true_pending_now"]))
        return "provider", "%s -> `%s`; %s" % (view, d["reply"]["result"], truth)
    if ev == "dispatch":
        return "client", "dispatches **%s**%s" % (_short(d["attempt_id"]), (" (%s)" % d["reason"]) if d.get("reason") else "")
    if ev == "status_read":
        return "client", "issues status read"
    if ev == "belief":
        return "client", "belief -> **%s**" % d["belief"]
    if ev == "conflict":
        return "client", "conflict recorded for %s (commit wins)" % _short(d["evidence"]["attempt_id"])
    if ev == "dispatch_refused":
        return "client", "dispatch refused (budget)"
    if ev == "horizon":
        return "scorer", "H reached: final belief `%s`" % d["belief"]
    if ev == "ledger_entry":
        return "scorer", "ledger: %s (%s, %s) at t = %s%s" % (d["effect_id"], e["op"], _short(d["attempt_id"]),
                                                            d["commit_time"], " [violation]" if d["violation"] else "")
    if ev in ("observe", "not_observed"):
        o = d["obs"]
        typ = o["type"]
        if typ in ("dispatched",):
            return None
        if typ == "start":
            text = "operation %s starts" % o["op_key"]
        elif typ == "timeout":
            text = "**timeout** for %s (ambiguous)" % _short(o["attempt_id"])
        elif typ == "response":
            text = "response `%s` for %s%s" % (o["kind"], _short(o["attempt_id"]),
                                               (" (effect %s)" % o["effect_id"]) if o.get("effect_id") else "")
        elif typ == "status":
            if o["result"] == "found":
                text = "status reply **`found`** (%s, %s)" % (_short(o["attempt_id"]), o["effect_id"])
            else:
                text = "status reply **`not_found`**, terminal_attempts [%s]" % ", ".join(_short(a) for a in o["terminal_attempts"])
        elif typ == "webhook":
            text = "webhook `%s` seq %s for %s (%s)" % (o["event"], o["provider_seq"], _short(o["attempt_id"]), o["event_id"])
        elif typ == "timer":
            text = "timer `%s` fires" % o["tag"]
        else:
            text = typ
        if ev == "not_observed":
            return "client", "(after H, not observed) " + text
        return "client", text
    return None


def timeline_md(sim, op="op-1"):
    rows = {}
    for e in sim.trace:
        if e["op"] not in (op, None):
            continue
        dsc = describe(e)
        if dsc is None:
            continue
        col, text = dsc
        rows.setdefault(e["t"], {"provider": [], "client": [], "scorer": []})[col].append(text)
    lines = ["| t | Provider knows | Client (policy) sees | Private scorer records |", "|---|---|---|---|"]
    for t in sorted(rows):
        r = rows[t]
        lines.append("| %d | %s | %s | %s |" % (t, "; ".join(r["provider"]) or "-", "; ".join(r["client"]) or "-",
                                                 "; ".join(r["scorer"]) or "-"))
    return "\n".join(lines)


